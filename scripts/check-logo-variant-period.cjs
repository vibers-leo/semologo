const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require('typescript');
const exportsForModule = {};
const source = fs.readFileSync('src/lib/logo-variant-period.ts', 'utf8');
const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
vm.runInNewContext(code, { exports: exportsForModule });
const { logoVariantPeriod: period, groupLogoVariantsByPeriod: groups } = exportsForModule;
const current = { key: 'current', current_artwork: true };
const unknown = { key: 'unknown', label: '이전 CI라는 제목만으로 판정하지 않음' };
const old = { key: 'old', historical: true };
assert.equal(period(unknown), 'undated');
assert.equal(period({ current_artwork: false }), 'undated');
assert.equal(period({ historical: true, current_artwork: true }), 'historical');
assert.equal(period({ usage: 'historical-logo' }), 'historical');
const ordinary = [unknown, current];
assert.equal(groups(ordinary).length, 1);
assert.equal(groups(ordinary)[0].period, 'all');
assert.equal(groups(ordinary)[0].variants.map(v => v.key).join(','), 'unknown,current');
const input = [old, unknown, current, { ...current, key: 'current-2' }];
const grouped = groups(input);
assert.equal(grouped.map(g => g.period).join(','), 'current,undated,historical');
assert.equal(grouped[0].variants.map(v => v.key).join(','), 'current,current-2');
assert.equal(input.map(v => v.key).join(','), 'old,unknown,current,current-2', 'never reorder the manifest in place');
assert.equal(groups([old])[0].period, 'historical');
assert.equal(groups([old]).length, 1, 'no empty section headings');
assert.equal(groups([])[0].variants.length, 0);
console.log('PASS: explicit period flags, unknown stays undated, conflicting flags, stable ordering, no empty groups and unchanged galleries without history');
